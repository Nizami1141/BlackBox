// I2C-адаптер HW-61 (PCF8574T) на плате экрана.
//      LCD GND -> GND платы
//      LCD VCC -> 5 В
//      LCD SDA -> преобразователь уровней -> GPIO 47
//      LCD SCL -> преобразователь уровней -> GPIO 3
//
// ПИТАНИЕ ТОЛЬКО 5 В. У HD44780 схема смещения ЖК-панели рассчитана на
// VDD = 5 В, и вывод контраста V0 отсчитывается относительно него. При
// 3.3 В подстроечнику не хватает диапазона, чтобы вывести сегменты в
// видимую область — экран остаётся пустым в любом положении ручки.
// Резистор подсветки тоже подобран под 5 В. Сама PCF8574 работает и от
// 2.5 В, но панель — нет, и это разные вещи.
//
// СЛЕДСТВИЕ: линии I2C подтянуты резисторами адаптера к его питанию,
// то есть к 5 В, а GPIO ESP32-S3 к 5 В не толерантны (абсолютный максимум
// VDD + 0.3 = 3.6 В). Нужен двунаправленный преобразователь уровней —
// модуль на BSS138, четыре канала, стоит копейки:
//
//      3.3 В платы -> LV        HV  <- 5 В
//      GPIO 47     -> LV1      HV1  -> SDA адаптера
//      GPIO 21     -> LV2      HV2  -> SCL адаптера
//      GND общая с обеих сторон
//
// Прямое подключение без преобразователя обычно живёт (подтяжка 4.7 кОм
// ограничивает ток в защитный диод входа примерно 0.3 мА), но это работа
// за пределами спецификации. Пост на границе должен стоять годами.
//
// Выпаивать подтяжки и вешать их на 3.3 В — не выход: у PCF8574 порог
// единицы VIH = 0.7 x VDD, при питании 5 В это 3.5 В, и уровень 3.3 В
// оказывается ниже гарантированного порога.
#if INTERBOARD_GATEWAY
  #define LCD_SDA_PIN    32
  #define LCD_SCL_PIN    33
#else
  #define LCD_SDA_PIN    47
  #define LCD_SCL_PIN    3
#endif
// 0 = искать адрес автоматически (0x27 у PCF8574T, 0x3F у PCF8574AT).
#define LCD_I2C_ADDR     0

// ---------------------------------------------------------------------------
//  ЖИВУЧЕСТЬ ШИНЫ ЭКРАНА — почему это не косметика
//
//  Экран, который не отвечает СОВСЕМ, безобиден: адрес не найдётся, и все
//  обращения будут молча пропускаться. Опасен промежуточный случай — адрес
//  отозвался, а дальше шина работает через раз. Именно это и даёт питание
//  адаптера 5 В без преобразователя уровней.
//
//  Считаем цену. Один вывод двух строк — около 200 транзакций I2C. На
//  исправной шине это 50 мс. На зависшей каждая транзакция упирается
//  в таймаут Wire, и при заводских 50 мс одно сообщение занимает ДЕСЯТЬ
//  СЕКУНД. Рисуется экран в той же задаче, которая опрашивает сканер, —
//  значит все эти секунды прочитанный штрихкод лежит в буфере UART, и
//  забрать его некому. Снаружи: «из-за экрана не читается штрихкод».
//
//  Поэтому: короткий таймаут, счётчик сбоев подряд и отключение экрана,
//  если он перешёл порог. Пост важнее экрана.
// ---------------------------------------------------------------------------
#define LCD_I2C_TIMEOUT_MS   10     // таймаут одной транзакции (было 50 по умолчанию)
#define LCD_MAX_FAILS        8      // столько сбоев подряд = экран отключаем
#define LCD_RETRY_MS         30000  // и раз в столько пробуем поднять заново

