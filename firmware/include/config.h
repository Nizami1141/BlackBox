// ===========================================================================
//  СКАНЕР ШТРИХКОДОВ GM67
//
//  Подключение (разъём UART на плате сканера, 4 контакта):
//      GM67  5V   -> 5V платы (или внешние 5 В, сканер ест 180 мА)
//      GM67  TX   -> GPIO 1   (вход ESP32)      ЛИНИИ ПЕРЕКРЕЩИВАЮТСЯ!
//      GM67  RX   <- GPIO 2   (выход ESP32)
//      GM67  GND  -> GND платы (общая земля обязательна)
//
//  ВНИМАНИЕ ПРО УРОВНИ: перед подключением измерьте мультиметром напряжение
//  на выводе TX сканера в покое (питание подано, линии данных НЕ подключены).
//    3.2-3.4 В — подключайте напрямую;
//    4.7-5.1 В — обязателен делитель 1 кОм / 2 кОм на линии GM67 TX -> GPIO 1,
//                иначе вы сожжёте вход ESP32, он не терпит 5 В.
//
//  Пины 1 и 2 выбраны потому, что камера занимает 4-18, UART0 (43/44) занят
//  логом, а 19/20 — это нативный USB. Если у вашей платы 1/2 заняты, возьмите
//  любые свободные и впишите сюда.
// ===========================================================================
#define GM67_UART_NUM    1        // аппаратный UART1 (UART0 занят логом)
#if INTERBOARD_GATEWAY
  #define GM67_RX_PIN    16       // ESP32 слушает   <- TX сканера
  #define GM67_TX_PIN    17       // ESP32 говорит   -> RX сканера
#else
  #define GM67_RX_PIN    1        // ESP32 слушает   <- TX сканера
  #define GM67_TX_PIN    2        // ESP32 говорит   -> RX сканера
#endif
#define GM67_BAUD        9600     // заводское значение GM67

// Диагностика автономного Ethernet-поста: не посылать GM67 никаких команд
// настройки, запуска, остановки или сна. Принимаем только UART-штрихкод
// после успешного распознавания лица; всё полученное раньше отбрасываем.
// Сканер должен уже быть в Continuous mode и сам включать луч. Если он
// сохранён в Host mode, без команд он не начнёт читать — верните 0.
// На BLE-прошивку этот флаг не влияет.
#define GM67_PASSIVE_UART_MODE  1

// Записать настройки во флеш самого сканера. Держите 1 только ОДИН раз,
// потом верните 0: флеш сканера не бесконечный.
#define GM67_WRITE_CONFIG_TO_FLASH  0

// ---------------------------------------------------------------------------
//  РАЗРЕШАТЬ ЛИ КОМАНДУ СНА СКАНЕРУ
//
//  0 = команда сна (0xEB) не уходит НИКОГДА, ни при загрузке, ни после
//      чтения кода. Сканер ест свои 180 мА круглосуточно.
//  1 = как было: усыплять между проверками.
//
//  Почему по умолчанию 0. Признак «он спит» живёт в оперативной памяти
//  ESP32. Пока сканер питался от платы, сброс платы был и его сбросом.
//  Теперь питание у сканера своё — сброс платы его НЕ будит. Значит после
//  перезагрузки модуль спит с прошлого запуска, а плата считает его бодрым
//  и шлёт команды, которые тот теряет. Отсюда три «сканер молчит» подряд
//  на исправном железе. Ловушка самоподдерживающаяся: в конце загрузки
//  сканер усыплялся снова.
//
//  Питание у сканера внешнее, так что 180 мА круглосуточно здесь допустимы.
//  Вернуть 1 можно будет, когда связь по UART станет устойчивой.
#define GM67_ALLOW_SLEEP            0

// ---------------------------------------------------------------------------
//  САМОПРОВЕРКА UART (loopback). Решает спор «виноват сканер или плата».
//
//  Как проверить:
//    1. ОТКЛЮЧИТЕ сканер от пинов 1 и 2.
//    2. Соедините GPIO 1 и GPIO 2 между собой одной перемычкой.
//    3. Поставьте здесь 1, прошейте, посмотрите лог.
//
//  Плата отправит строку в свой же TX и попробует прочитать её своим RX.
//    ПРОЙДЕНА  -> пины, UART и код работают. Проблема в сканере или проводке.
//    ПРОВАЛЕНА -> проблема на стороне платы: не те пины или они заняты.
//
//  После проверки верните 0 и снимите перемычку.
// ---------------------------------------------------------------------------
#define GM67_SELFTEST    0

// Автоматически гасить луч, если сотрудник так и не поднёс штрихкод.
// Страховка на случай, если сервер отвалился и не прислал "SCAN OFF":
// луч не должен гореть вечно (это и батарею сканера ест, и слепит людей).
// Должно быть чуть больше, чем session.ttl_seconds на сервере.
#define GM67_SCAN_WINDOW_MS  120000

// Отладка: печатать КАЖДЫЙ байт, пришедший от сканера, в hex.
// Включайте, когда сканер пищит и читает, а на плату ничего не приходит.
// Сразу видно: байтов нет вовсе (провода/уровни/режим USB), пришёл мусор
// (не тот баррейт) или пришёл нормальный текст (тогда дело в разборе).
// В обычной работе держите 0 — иначе лог захлебнётся.
#define GM67_DEBUG_RAW   0

// Минимальная длина строки, которую плата считает настоящим штрихкодом.
// Короче — почти наверняка обрывок служебного кадра сканера: в Host Mode
// сканер отвечает подтверждением на каждую команду, и байт контрольной
// суммы после фильтра «только печатный ASCII» превращается в одиночный
// символ вроде '(' или '$'.
//
// Служебный кадр 04 D0 04 00 FF 28 даёт максимум ДВА печатных символа,
// поэтому 3 отсекает его гарантированно. Больше ставить незачем: основную
// работу теперь делает проверка «в коде есть буква или цифра»
// (src/gm67.cpp, acceptable), а длина — только страховка. Раньше здесь
// стояло 4, и трёхсимвольный номер груза молча пропадал бы.
#define GM67_MIN_CODE_LEN    3

// Окно тишины после включения луча — сколько миллисекунд не верить
// приходящим данным.
//
// ВЫКЛЮЧЕНО (0), и это осознанно. Идея была отсечь ответ сканера на
// START_DECODE, но окно съедало настоящие коды: сотрудник держит груз перед
// сканером ЗАРАНЕЕ, код читается за 60–120 мс после вспышки луча и попадает
// ровно в окно недоверия. А в Host Mode сеанс чтения после удачного декода
// заканчивается — то есть выброшенный код был единственным. Снаружи это
// выглядело как «сканер пищит, а в журнале пусто».
// Разбор целиком — в src/gm67.cpp у acceptable().
#define GM67_GUARD_MS        0

// Раз в сколько миллисекунд заново взводить чтение, пока ждём штрихкод.
//
// В Host Mode START_DECODE запускает ОДИН сеанс чтения, а не включает луч
// насовсем. Сеанс кончается либо удачным декодом, либо по длительности
// одиночного скана (PX_SINGLE_SCAN, у нас 5 секунд). Ждём же мы штрихкод
// до 45 секунд — и без перевзвода сканер через пять секунд тихо переставал
// читать, а плата продолжала ждать того, чего уже не могло случиться.
//
// 2000 мс: заметно чаще, чем истекает пятисекундный сеанс, и достаточно
// редко, чтобы команда (около 170 мс с учётом пробуждения и вычитки ответа)
// не занимала канал.
#define GM67_REARM_MS        2000

// Сколько секунд игнорировать повторное чтение ТОГО ЖЕ кода.
// Без этого сканер будет слать один и тот же штрихкод снова и снова,
// пока он лежит перед объективом.
#define GM67_SAME_CODE_IGNORE_S     3

