// ===========================================================================
//  НАГРЕВ КАМЕРЫ
//
//  Откуда берётся тепло. OV5640 не имеет своего генератора — его тактирует
//  ESP32 сигналом XCLK. Пока клок идёт, внутри сенсора работает всё: ФАПЧ,
//  дерево тактирования, аналоговая часть, встроенный кодировщик JPEG.
//  И он снимает кадры непрерывно, около тридцати в секунду, независимо от
//  того, забирает их кто-нибудь или нет.
//
//  На посту из этих тридцати кадров в секунду используется один раз в
//  несколько минут. Всё остальное греет коробку.
//
//  Три состояния (подробности в src/camera.h):
//      ACTIVE   снимаем, несколько сотен миллисекунд за проверку
//      STANDBY  сенсор в программном сне, XCLK снят, драйвер жив
//      OFF      драйвер остановлен целиком
//
//    0 = камера включена всегда (как в самой первой версии)
//    1 = STANDBY между кадрами
//    2 = STANDBY между кадрами + OFF после долгого простоя   ← по умолчанию
// ===========================================================================
#define CAM_POWER_PLAN    2

// Частота тактирования сенсора.
//
// БЫЛО 10 МГц — и это оказалось ошибкой, из-за неё кадры уходили в белизну.
// Разбор здесь, чтобы не наступить второй раз.
//
// Выдержка у OV5640 задаётся не в миллисекундах, а в СТРОКАХ кадра. Длина
// строки считается от пиксельного клока, а он получается из XCLK через ФАПЧ.
// Уполовинив XCLK, я уполовинил пиксельный клок и тем самым ВДВОЕ УДЛИНИЛ
// строку. Один и тот же регистр выдержки стал означать вдвое больше света.
// Автоматика это отрабатывает — но не мгновенно, ей нужно несколько кадров.
// А кадры при 10 МГц идут вдвое реже. То есть я одновременно создал ошибку
// экспозиции и вдвое замедлил её исправление.
//
// Выигрыш при этом был мнимый. Тепло от камеры берётся из ДОЛИ ВРЕМЕНИ,
// когда идёт XCLK, а не из его частоты. Раньше камера тактировалась
// круглосуточно — вот там 20 МГц против 10 действительно решали. Теперь она
// живёт доли секунды на проверку и спит остальное время: разница между
// 10 и 20 МГц в пересчёте на сутки — единицы милливатт. Платить за них
// белыми кадрами незачем.
//
// 20 МГц — родной режим OV5640, все тайминги сенсора рассчитаны под него.
#define CAM_XCLK_HZ       20000000

// Количество буферов кадра. Двойная буферизация нужна видеопотоку, чтобы
// кадры шли непрерывно. Здесь снимается один кадр за раз, и второй буфер
// означает лишний отснятый кадр — лишнюю работу сенсора и лишнее тепло.
#define CAM_FB_COUNT      1

// --- тайминги пробуждения --------------------------------------------------
// БЫЛО: 120 мс и один кадр «из сна», потому что я считал, что сохранённые
// регистры избавляют от повторной сходимости. Практика показала обратное:
// программный сон (0x3008) останавливает конвейер сенсора, и после выхода
// автоматика экспозиции стартует заново — сохранились ЗНАЧЕНИЯ регистров,
// но не состояние петли регулирования. Первый кадр после сна приходит
// пересвеченным, второй ещё пересвечен, к третьему-четвёртому приходит
// в норму. Одного выброшенного кадра не хватало, и пересвеченный уходил
// на сервер как есть — отсюда «сначала фоткал нормально, потом белое».
//
// Ниже — верхние границы. Сколько на самом деле выбросить, решает уже сама
// прошивка: она смотрит на размер JPEG (см. CAM_MIN_JPEG_BYTES) и
// останавливается, как только картинка стабилизировалась. В хорошем свете
// это два кадра, в плохом — все четыре.
#define CAM_PLL_LOCK_MS       15    // ФАПЧ сенсора захватывает частоту
#define CAM_WARM_SETTLE_MS    250
#define CAM_WARM_SKIP_FRAMES  4

// Из полного выключения: сенсор стартует с заводских настроек, автоматике
// надо сойтись с нуля.
#define CAM_COLD_SETTLE_MS    400
#define CAM_COLD_SKIP_FRAMES  5

// ---------------------------------------------------- проверка кадра на глаз
// Пересвеченный кадр — это почти равномерное белое поле, а равномерное поле
// JPEG сжимает во много раз сильнее нормальной картинки. Кадр VGA с лицом
// при качестве 12 весит 20–45 КБ; кадр, ушедший в белизну, — 2–6 КБ.
// Полностью чёрный, кстати, тоже: у обеих аварий одна примета — кадр
// подозрительно лёгкий.
//
// Это даёт дешёвую проверку без анализа пикселей: если JPEG меньше порога,
// автоматика ещё не сошлась — выбрасываем кадр и берём следующий.
//
// Если у вас часто светлый однотонный фон (белая стена вплотную), поставьте
// порог ниже, иначе прошивка будет выбрасывать нормальные кадры. Реальные
// размеры видно в логе: [cam] кадр 640x480, 31204 байт.
//   VGA  качество 12 -> 8000
//   QVGA качество 12 -> 2500
//   SVGA качество 12 -> 12000
#define CAM_MIN_JPEG_BYTES    8000

// Сколько раз пересниять, если кадр не прошёл проверку выше.
