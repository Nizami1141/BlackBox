// ===========================================================================
//  ЭТАПНОСТЬ: что именно работает в покое
//
//  Правило поста: между проверками не работает НИЧЕГО, а по нажатию кнопки
//  узлы включаются по очереди, в том порядке, в каком нужны. Каждый
//  переключатель ниже — отдельный узел, и у каждого своя цена.
//
//  Порядок одного прохода:
//
//      покой:  экран погашен, сеть спит, камера выключена, сканер спит
//        |
//      кнопка
//        |
//      1. экран           <- зажигается первым, человек сразу видит отклик
//      2. сеть            <- PHY просыпается, ждём автопереговоры
//      3. камера          <- включается, снимает, СРАЗУ выключается
//      4. сеть            <- отправка кадра, ожидание ответа
//      5. экран           <- вердикт обновляется ПЕРЕД включением сканера
//      6. сканер          <- луч зажигается только здесь
//      7. сеть            <- отправка штрихкода
