//
// Задумка была такая: перевести PHY в Power Down (регистр PHYCFGR, OPMDC=110)
// и снять около 130 мА — самый крупный оставшийся потребитель в покое.
// Уснуть получалось. Проснуться — нет: после пробуждения микросхема
