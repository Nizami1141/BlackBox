// ===========================================================================
//  Управление питанием поста
//
//  ---------------------------------------------------------------------
//  Где на самом деле уходит энергия
//  ---------------------------------------------------------------------
//  Считать надо не по ощущениям, а по потребителям. Для этого поста:
//
//      GM67 сканер     ~180 мА  и это КРУГЛОСУТОЧНО. Он не засыпает сам,
//                               даже когда луч погашен. Самый крупный
//                               потребитель во всей схеме.
//      W5500           ~130 мА  постоянно, пока держит линк
//      OV5640          ~100 мА  пока идёт XCLK — то есть тоже круглосуточно,
//                               если камеру не выключать
//      ESP32-S3        40-80 мА на 240 МГц без радио
//      LCD подсветка   ~25 мА
//
//  Итого в покое набегало под 450 мА, причём проверка бывает раз в
//  несколько минут. Отсюда и нагрев: почти вся эта мощность превращается
//  в тепло внутри одной коробки.
//
//  Что делаем, по убыванию выигрыша:
//    1. Усыпляем сканер          -180 мА  (самое крупное)
//    2. Выключаем камеру         -100 мА  (см. CAM_POWER_PLAN в config.h)
//    3. Снижаем частоту CPU      -30 мА
//    4. Лёгкий сон до нажатия    -40 мА   (CPU почти встаёт)
//
//  W5500 не трогаем: у него есть режим пониженного потребления, но тогда
//  теряется линк, а вместе с ним и возможность узнать, что сервер жив.
//  Для поста на границе это плохой размен.
//
//  ---------------------------------------------------------------------
//  Осторожно с частотой CPU и камерой
//  ---------------------------------------------------------------------
//  XCLK для камеры формирует блок LEDC, а он тактируется от шины APB.
//  Смена частоты процессора меняет APB — и XCLK уезжает вслед за ней,
//  вплоть до испорченных кадров. Поэтому частоту трогаем ТОЛЬКО когда
//  камера выключена: поднимаем до пробуждения камеры, опускаем после того,
//  как она уснула. Порядок в checkpoint.cpp именно такой.
// ===========================================================================
#pragma once

#include <Arduino.h>

namespace power {

void begin();

// Поднять частоту перед тяжёлой работой (съёмка кадра, отправка по сети).
// Звать ДО cam::wake().
void active();

// Вернуть пониженную частоту. Звать ПОСЛЕ того, как камера уснула.
void idle();

// Лёгкий сон до нажатия кнопки или до истечения timeoutMs.
// Возвращает true, если разбудила кнопка.
//
// Что переживает лёгкий сон: содержимое RAM, состояние периферии, показания
// millis(). Экран продолжает показывать своё — HD44780 держит картинку сам,
// без участия процессора. W5500 линк не теряет.
//
// Чего не переживает: вывод в Serial во время самого сна. При отладке это
// выглядит как «плата умерла», поэтому POWER_MODE 2 включайте, когда всё
// остальное уже работает.
bool sleepUntilButton(int buttonPin, uint32_t timeoutMs);

// Текущая частота — для строки статуса.
uint32_t cpuMhz();

}  // namespace power
