// ===========================================================================
//  LCD 1602 через I2C-адаптер HW-61 (микросхема PCF8574T)
//
//  Экран нужен по простой причине: на границе компьютера рядом не будет.
//  Сотрудник должен видеть вердикт на самом посту, а не на чужом мониторе.
//
//  ---------------------------------------------------------------------
//  Про азербайджанские буквы — это главная сложность этого файла
//  ---------------------------------------------------------------------
//  В знакогенераторе HD44780 (ROM A00) азербайджанских букв нет вообще:
//  ə, ı, ö, ü, ç, ş, ğ там отсутствуют. Ни одна из них не выведется, если
//  просто послать её байты — на экране будет мусор или пропуски.
//
//  Решение: у HD44780 есть CGRAM — восемь программируемых знакомест 5x8.
//  Нужных букв ровно семь, и они туда помещаются целиком. Восьмое место
//  остаётся свободным на будущее.
//
//  Текст в программе пишется обычным UTF-8, а lcd::print() на лету
//  переводит его в коды экрана: латиница уходит как есть, семь особых
//  букв подменяются на свои знакоместа. Заглавные Ə, I, Ö, Ü, Ç, Ş, Ğ
//  выводятся строчными глифами — отдельных мест на них не осталось,
//  а читаемость от этого страдает несильно.
//
//  ---------------------------------------------------------------------
//  Разводка адаптера HW-61 (стандартная для PCF8574-бэкпаков)
//  ---------------------------------------------------------------------
//      P0 -> RS      P4 -> D4
//      P1 -> RW      P5 -> D5
//      P2 -> E       P6 -> D6
//      P3 -> подсветка   P7 -> D7
//
//  Адрес на шине: 0x27 у PCF8574T, 0x3F у PCF8574AT. Какой именно стоит
//  у вас — определяется автоматически при lcd::begin().
// ===========================================================================
#pragma once

#include <Arduino.h>

namespace lcd {

// Поднять экран. Возвращает false, если по I2C никто не ответил
// (типовая причина — перепутаны SDA и SCL либо не подано питание).
bool begin(int sda, int scl, uint8_t addr = 0);

bool ok();

// Адрес, по которому экран реально нашёлся. Печатается в лог при старте:
// удобно, когда попался адаптер с нестандартной перемычкой адреса.
uint8_t address();

// Сколько транзакций I2C завершились ошибкой с момента включения.
// Растёт — шина работает на грани (чаще всего это питание адаптера 5 В
// без преобразователя уровней на SDA/SCL). Подробности в lcd.cpp
// у expanderWrite(): полудохлая шина тормозит не только экран.
uint32_t errors();

// Вывести строку (0 или 1). Текст в UTF-8, длиннее 16 символов обрезается.
// Строка дополняется пробелами до конца — иначе от прошлого сообщения
// остаётся хвост, и на экране получается каша из двух фраз.
void print(uint8_t line, const String &utf8);

// Обе строки разом. Самый частый вызов: экран почти всегда меняется целиком.
void show(const String &line1, const String &line2 = "");

void clear();
void backlight(bool on);

// Показать сообщение и запомнить, когда его пора сменить на дежурное.
// Нужно, чтобы «Груз записан» не висело до следующего сотрудника.
void showFor(const String &line1, const String &line2, uint32_t ms);

// Вызывать из loop(): возвращает экран к дежурному сообщению, когда
// время showFor() вышло.
// Заново инициализировать панель HD44780, не трогая поиск адреса.
// Нужно против рассинхрона 4-битного режима: он не даёт ошибок на шине,
// но превращает весь текст в мусор до перезагрузки.
void resync();

void tick(const String &idleLine1, const String &idleLine2);

}  // namespace lcd
