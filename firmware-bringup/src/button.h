// ===========================================================================
//  Кнопка «Проверить» на посту
//
//  Схема подключения — самая простая из возможных:
//
//      GPIO ────┬──── кнопка ──── GND
//               │
//          внутренняя подтяжка к 3.3 В (включается программно)
//
//  Внешний резистор не нужен: у ESP32-S3 есть внутренний подтягивающий
//  резистор на каждом обычном GPIO. В покое на входе высокий уровень,
//  нажатие сажает его на землю.
//
//  ---------------------------------------------------------------------
//  Зачем нужен антидребезг
//  ---------------------------------------------------------------------
//  Механические контакты при замыкании «звенят» — за первые 5–20 мс
//  уровень скачет туда-сюда десятки раз. Без фильтрации одно нажатие
//  превратится в десяток срабатываний, и пост отправит на сервер пачку
//  кадров подряд. Здесь нажатие засчитывается, только если уровень
//  продержался стабильным DEBOUNCE_MS.
//
//  Длинное нажатие (по умолчанию 2 секунды) отдано под отмену: сотрудник
//  передумал или сканер завис — держит кнопку, пост возвращается в покой.
// ===========================================================================
#pragma once

#include <Arduino.h>

namespace btn {

void begin(int pin, bool activeLow = true);

// Вызывать часто (из основной задачи). Возвращает true ОДИН раз на нажатие.
bool pressed();

// То же для длинного удержания. Короткое нажатие при этом не засчитывается:
// иначе одно удержание давало бы и отмену, и новую проверку.
bool longPressed();

// Нажата ли прямо сейчас — для диагностики: если тут всегда true,
// кнопка замкнута накоротко или перепутана земля.
bool isDown();

}  // namespace btn
