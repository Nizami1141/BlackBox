//  Стенд: экран + кнопка + камера. Больше ничего.
//
//  Ни Ethernet, ни Bluetooth, ни сканера. Задача одна: довести до рабочего
//  состояния три узла и ИЗМЕРИТЬ, как греется плата, а не рассуждать об этом.
//
//  Когда здесь всё заработает — алгоритм камеры переносится в основной
//  проект как есть, файлы camera.cpp/h совместимы по интерфейсу.
// ===========================================================================
#pragma once

#define SERIAL_BAUD      115200

// ---------------------------------------------------------------- экран ---
#define ENABLE_LCD       1
#define LCD_SDA_PIN      47
#define LCD_SCL_PIN      21
#define LCD_I2C_ADDR     0        // 0 = искать адрес автоматически

// --------------------------------------------------------------- кнопка ---
#define ENABLE_BUTTON    1
#define BUTTON_PIN       14       // второй вывод кнопки — на GND

// --------------------------------------------------------------- камера ---
#define CAMERA_PRESET_FREENOVE_S3   1
#define CAMERA_PRESET_ESP32S3_EYE   0
#define CAMERA_PRESET_XIAO_S3       0
#define CAMERA_PRESET_CUSTOM        0

#define CAM_FRAMESIZE     FRAMESIZE_VGA   // 640x480 — то, что нужно для лица
#define CAM_JPEG_QUALITY  12
#define CAM_HMIRROR       0
#define CAM_VFLIP         0

// ===========================================================================
//  ТЕПЛО: три рычага, в порядке убывания эффекта
// ===========================================================================

// --- рычаг 1: частота тактирования сенсора --------------------------------
//
// XCLK — это клок, который ESP32 подаёт на камеру. От него напрямую зависит,
// сколько тактов в секунду переключается вся цифровая часть сенсора,
// а динамическая мощность КМОП-схемы пропорциональна частоте. Вдвое ниже
// частота — примерно вдвое меньше тепла.
//
// 20 МГц стоит во всех примерах и потому кочует из проекта в проект.
// Но 20 МГц нужны для видеопотока с высоким разрешением. Нам нужен ОДИН
// кадр VGA по нажатию кнопки — 10 МГц хватает с запасом, кадр просто
// снимается вдвое дольше, а этого никто не заметит.
//
// Если на 10 МГц пойдут битые или зелёные кадры — поднимите до 16 или 20.
// У некоторых экземпляров OV5640 нижняя граница выше паспортной.
#define CAM_XCLK_HZ       10000000

// --- рычаг 2: сколько времени сенсор вообще включён -----------------------
//
// Между съёмками драйвер камеры выключается целиком: снимается XCLK,
// сенсор остаётся без тактирования и почти ничего не потребляет.
//
// Значит греет он ровно столько, сколько длится одна съёмка. И вот эту
// длительность мы сокращаем адаптивно, а не фиксированной паузой:
// раньше стояло «подожди 350 мс и выброси 2 кадра» вслепую. Теперь
// прошивка смотрит на размер JPEG и заканчивает, как только экспозиция
// сошлась — обычно это 2-3 кадра вместо гарантированных четырёх.

// Сколько кадров максимум разрешено потратить на сходимость экспозиции.
// Достигли предела — берём последний, какой есть.
#define CAM_MAX_FRAMES        6

// Первые кадры сенсор отдаёт заведомо сырыми, их выбрасываем всегда.
#define CAM_ALWAYS_SKIP       1

// Экспозиция считается сошедшейся, когда размер JPEG двух подряд идущих
// кадров отличается меньше чем на столько процентов. Размер файла —
// хороший и дешёвый признак: тёмный и пересвеченный кадры сжимаются
// совсем по-разному, а как только автоматика встала — размер замирает.
#define CAM_SETTLE_PERCENT    8

// --- рычаг 3: минимальная пауза между съёмками ----------------------------
//
// Без неё достаточно зажать кнопку, чтобы камера работала непрерывно —
// и весь смысл выключения между кадрами пропадает.
#define CAM_MIN_INTERVAL_MS   1500

// --- защита по температуре -------------------------------------------------
//
// Выше этого порога съёмка запрещается до остывания. Для поста в закрытом
// корпусе летом это не теория: кристалл ESP32-S3 нормально живёт до 85 °C,
// но при 70 уже стоит перестать подбрасывать дров.
//
// ВАЖНО: датчик находится ВНУТРИ ESP32 и меряет его кристалл, а не корпус
// камеры. Это косвенный показатель — камера греет плату, плата греется.
// Абсолютную температуру модуля им не измерить, но динамику видно отлично.
#define CAM_TEMP_MAX_C        70.0f
#define CAM_TEMP_RESUME_C     62.0f    // снова разрешаем, когда опустится сюда

// --- частота процессора ----------------------------------------------------
//
// В покое пост просто ждёт нажатия — 80 МГц хватает. На съёмку поднимаем.
//
// ПОРЯДОК ВАЖЕН: частоту меняем только при ВЫКЛЮЧЕННОЙ камере. XCLK
// формирует блок LEDC, тактируемый от шины APB, а APB меняется вслед за
// частотой процессора. Поднимете частоту при работающей камере — XCLK
// уедет, и кадр придёт шумным.
#define CPU_MHZ_IDLE      80
#define CPU_MHZ_ACTIVE    240

// --- тепловой прогон -------------------------------------------------------
// Долгое нажатие кнопки (2 с) запускает автоматический прогон: снимок
// каждые CAM_SOAK_INTERVAL_MS, температура пишется в лог. Нужен, чтобы
// увидеть, выходит ли плата на полку или греется бесконечно.
#define CAM_SOAK_INTERVAL_MS  10000

