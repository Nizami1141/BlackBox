// ===========================================================================
//  Камера: съёмка кадров и управление нагревом
//
//  ---------------------------------------------------------------------
//  Откуда берётся тепло
//  ---------------------------------------------------------------------
//  OV5640 не имеет собственного генератора. Его тактирует ESP32 сигналом
//  XCLK, и пока этот клок идёт, внутри сенсора работает всё: система ФАПЧ,
//  дерево тактирования, аналоговая часть, встроенный кодировщик JPEG.
//  Сенсор при этом снимает кадры непрерывно — примерно тридцать в секунду —
//  независимо от того, забирает их кто-нибудь или нет.
//
//  На посту, где проверка бывает раз в несколько минут, из тридцати кадров
//  в секунду используется один. Остальные греют коробку.
//
//  ---------------------------------------------------------------------
//  Три состояния вместо двух
//  ---------------------------------------------------------------------
//  В прошлой версии было «включено / выключено», и выключение означало
//  полную остановку драйвера. Работало, но платило 1.1 секунды за каждое
//  пробуждение и каждый раз заново теряло настройки экспозиции.
//
//      ACTIVE   снимаем. Несколько сотен миллисекунд за проверку.
//
//      STANDBY  сенсор в программном сне (регистр 0x3008), XCLK остановлен.
//               Драйвер при этом жив, настройки экспозиции сохранены.
//               Просыпается за ~180 мс. Основное состояние покоя.
//
//      OFF      драйвер остановлен целиком. Сюда уходим после долгого
//               простоя: экономия чуть больше, но пробуждение ~1.1 с.
//
//  Почему STANDBY лучше полного выключения для обычной работы: не надо
//  заново поднимать драйвер, а это секунда с лишним на каждое нажатие.
//
//  ---------------------------------------------------------------------
//  Чего сон НЕ сохраняет (грабли, на которые я наступил)
//  ---------------------------------------------------------------------
//  Сначала здесь было написано, что из сна регистры экспозиции сохраняются,
//  поэтому хватает короткой паузы и одного выброшенного кадра. Это оказалось
//  неверно, и проявилось характерно: первый снимок после включения выходил
//  нормальным, а все следующие — белым пятном.
//
//  Сохраняются ЗНАЧЕНИЯ регистров. Не сохраняется состояние петли
//  регулирования: программный сон (0x3008) останавливает конвейер сенсора
//  целиком, и после выхода автоматика экспозиции стартует заново. Первые
//  два-три кадра приходят пересвеченными независимо от того, что записано
//  в регистрах. Один выброшенный кадр эту фазу не перекрывал, и пересвеченный
//  уходил на сервер как есть.
//
//  Поэтому сейчас: тёплое пробуждение по времени почти равно холодному,
//  число выбрасываемых кадров решается не константой, а по факту — прошивка
//  смотрит на размер JPEG и останавливается, когда картинка устоялась
//  (settleFrames в camera.cpp). Плюс готовый кадр ещё раз проверяется на
//  «подозрительно лёгкий» и при необходимости переснимается.
//
//  ---------------------------------------------------------------------
//  Тонкость с частотой процессора
//  ---------------------------------------------------------------------
//  XCLK формирует блок LEDC, а его делитель считается от частоты шины APB,
//  которая меняется вместе с частотой процессора. Если просто возобновить
//  остановленный таймер после перехода с 80 на 240 МГц, XCLK окажется
//  втрое выше положенного, и кадр придёт искажённым.
//
//  Поэтому при каждом пробуждении частота XCLK задаётся заново
//  (ledc_set_freq): делитель пересчитывается под текущий APB, и какой бы
//  ни была частота процессора, сенсор получает ровно то, что нужно.
// ===========================================================================
#pragma once

#include <Arduino.h>
#include <esp_camera.h>

namespace cam {

enum class State { OFF, STANDBY, ACTIVE };

bool  begin();
bool  ok();
State state();
const char *stateName();

// --- основной способ снять кадр -------------------------------------------
// Разбудить -> дать автоматике сойтись -> снять -> усыпить обратно.
// Буфер в PSRAM освобождает вызывающий через free().
// Камера включена ровно то время, которое нужно для одного кадра.
uint8_t *snapshotOnce(size_t *outLen, uint16_t *outW, uint16_t *outH);

// --- ручное управление (нужно видеопотоку) --------------------------------
bool wake();          // STANDBY или OFF -> ACTIVE
void sleep();         // ACTIVE -> STANDBY
void off();           // -> OFF, полная остановка драйвера

// Вызывать из loop(): переводит камеру из STANDBY в OFF после долгого
// простоя. Без этого она осталась бы в лёгком сне навсегда.
void tick();

// --- кадры для тех, кому нужен прямой доступ (MJPEG-поток) ----------------
camera_fb_t *acquire(uint32_t timeoutMs = 2000);
void         release(camera_fb_t *fb);
uint8_t     *snapshot(size_t *outLen, uint16_t *outW, uint16_t *outH);

void setQuality(int q);

// --- наблюдение за нагревом -----------------------------------------------
// Температура кристалла ESP32 в градусах. Показания грубые (разброс
// в несколько градусов), но для ответа на вопрос «греется или нет»
// этого достаточно: важна не абсолютная цифра, а как она меняется.
float    chipTemp();
uint32_t shotsTaken();
// Сколько кадров отбраковано как пересвеченные (см. CAM_MIN_JPEG_BYTES).
// Если растёт вместе с числом снимков — света на посту не хватает
// или порог выставлен слишком высоко.
uint32_t rejected();
size_t   lastLen();         // размер последнего кадра в байтах
uint32_t lastWakeMs();      // сколько заняло последнее пробуждение
uint32_t activeMsTotal();   // сколько всего камера была включена

}  // namespace cam
