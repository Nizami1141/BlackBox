// BLE GATT-сервер: приём команд и отправка фотографий чанками.
#pragma once

#include <Arduino.h>

namespace blep {

// Поднять BLE-сервер и начать рекламу (advertising).
void begin(const char *deviceName);

// Подключён ли клиент и подписан ли он на уведомления с данными.
bool isReady();

// Отправить один JPEG. Блокирующая функция, вызывать из своей задачи.
// Возвращает false, если клиент отключился по ходу передачи.
bool sendPhoto(const uint8_t *jpeg, size_t len, uint16_t w, uint16_t h);

// Отправить прочитанный штрихкод. Уходит по той же характеристике, что и
// фотографии, но отдельным типом пакета — приёмник их различает.
bool sendBarcode(const String &text);

// Отправить строку статуса (JSON) в CHR_STATUS.
void sendStatus(const String &json);

uint32_t barcodesSent();

// --- управление сканером из режима КПП ------------------------------------
// Сервер шлёт "SCAN ON" после того, как узнал лицо, и "SCAN OFF" после того,
// как штрихкод записан. До "SCAN ON" луч сканера погашен и код прочитать
// нельзя — это и есть техническая гарантия связки «лицо → груз».
bool scannerWanted();          // текущее желаемое состояние сканера
void setScannerWanted(bool on);

// Сообщить серверу о событии на посту. Сейчас единственное — "BUTTON":
// сотрудник нажал кнопку у камеры, и проверку надо начать. Без этого
// проверку мог бы запустить только оператор мышью на сайте.
bool sendEvent(const char *name);

// --- строки для экрана, присланные сервером --------------------------------
// Колбэк BLE выполняется в стеке Bluedroid, и трогать оттуда шину I2C
// нельзя — экран надо рисовать из обычной задачи. Поэтому колбэк только
// складывает текст сюда, а main.cpp его забирает и выводит.
bool     takeLcdUpdate(String &line1, String &line2, uint32_t &holdMs);

// --- состояние, которым управляет GUI через команды ---
bool     photoEnabled();
void     setPhotoEnabled(bool on);
uint32_t photoInterval();
bool     takeShotRequested();   // одноразовый флаг: читает и сбрасывает
uint32_t framesSent();

// Вызывается из main, когда пришла команда изменить качество JPEG.
// Возвращает запрошенное качество или 0, если запроса не было.
int  pendingQuality();

}  // namespace blep
