// ===========================================================================
//  Автономный сценарий поста (режим Ethernet)
//
//  Здесь плата ведёт проверку сама, без ноутбука рядом. Порядок:
//
//      покой  ──кнопка──▶  кадр  ──▶  сервер опознаёт  ──┬─ не узнал ─▶ отказ
//                                                        │
//                                                        └─ узнал ─▶ луч сканера
//                                                                      │
//                                                          штрихкод ───┘
//                                                                      │
//                                                            сервер пишет
//                                                             в журнал
//
//  ---------------------------------------------------------------------
//  Что решает плата, а что сервер
//  ---------------------------------------------------------------------
//  Плата только СЕКВЕНСИРУЕТ: сняла, отправила, показала ответ, включила
//  луч, отправила код. Решения принимает сервер, и это принципиально:
//
//    * узнан человек или нет — решает сервер, у платы нет ни базы, ни модели;
//    * запись в журнал сервер сделает ТОЛЬКО по действующему session token,
//      а токен выдаётся исключительно после успешного опознания.
//
//  Поэтому даже подменённая прошивка не сможет записать «сотрудник проверил
//  груз» без реального опознания: она может зажечь луч когда угодно, но
//  токена у неё не будет, и сервер такой скан отвергнет.
//
//  ---------------------------------------------------------------------
//  Порядок операций с питанием — не переставлять
//  ---------------------------------------------------------------------
//  XCLK камеры формирует LEDC, тактируемый от шины APB, а частота APB
//  меняется вместе с частотой процессора. Поэтому:
//
//      power::active()  →  cam::wake()  →  снять  →  cam::sleep()  →  power::idle()
//
//  Если поднять частоту после включения камеры, XCLK уедет и кадр
//  испортится — причём не отказом, а «шумным» изображением, по которому
//  распознавание честно ответит «лицо не найдено».
// ===========================================================================
#pragma once

#include <Arduino.h>

class GM67;

namespace checkpoint {

// scanner может быть nullptr, если сканер отключён флагом ENABLE_GM67.
void begin(GM67 *scanner);

// Вызывать из loop(). Внутри — ожидание кнопки (со сном, если POWER_MODE 2)
// и весь проход проверки целиком.
void loop();

// Called on the checkpoint task while idle; no verification or API request.
bool diagnoseLCD();

}  // namespace checkpoint
